/* ---------- GET SELECTED TOUR ---------- */

const urlParams =
  new URLSearchParams(window.location.search);

const selectedTour =
  urlParams.get("tour");

const tour =
  tourData[selectedTour];


/* ---------- PAGE ELEMENTS ---------- */

const tourName =
  document.getElementById("tourName");

const tourLocation =
  document.getElementById("tourLocation");

const tourImage =
  document.getElementById("tourImage");

const tourTitle =
  document.getElementById("tourTitle");

const tourDescription =
  document.getElementById("tourDescription");

const tourDuration =
  document.getElementById("tourDuration");

const tourPrice =
  document.getElementById("tourPrice");

const tourIncludes =
  document.getElementById("tourIncludes");


/* ---------- DISPLAY TOUR ---------- */

if (tour) {

  tourName.textContent =
    tour.name;

  tourLocation.textContent =
    tour.location;

  tourImage.src =
    tour.image;

  tourImage.alt =
    tour.name;

  tourTitle.textContent =
    tour.name;

  tourDescription.textContent =
    tour.description;

  tourDuration.textContent =
    tour.duration;

  tourPrice.textContent =
    tour.price + " per person";


  tourIncludes.innerHTML = "";


  tour.includes.forEach(function (item) {

    const li =
      document.createElement("li");

    li.textContent =
      item;

    tourIncludes.appendChild(li);

  });


} else {

  tourName.textContent =
    "Tour Not Found";

  tourLocation.textContent =
    "Please return to our tours page.";

  tourDescription.textContent =
    "The selected tour could not be found.";

}


/* ---------- BOOKING ELEMENTS ---------- */

const tourBookingForm =
  document.getElementById("tourBookingForm");

const bookingMessage =
  document.getElementById("bookingMessage");

const bookingSuccess =
  document.getElementById("bookingSuccess");

const numberOfTravelersInput =
  document.getElementById("numberOfTravelers");


/* ---------- PRICE CALCULATION ---------- */

function getBasePrice() {

  if (!tour) {
    return 0;
  }

  return Number(
    tour.price.replace(/[₦,]/g, "")
  );

}


function calculateTotalPrice(numberOfTravelers) {

  const basePrice =
    getBasePrice();

  return basePrice *
    Number(numberOfTravelers);

}


function formatPrice(amount) {

  return "₦" +
    amount.toLocaleString("en-NG");

}


/* ---------- SHOW PRICE PER PERSON ---------- */

if (tour) {

  tourPrice.textContent =
    formatPrice(getBasePrice()) +
    " per person";

}


/* ---------- BOOKING ---------- */

tourBookingForm.addEventListener(
  "submit",
  function (event) {

    event.preventDefault();


    const customerName =
      document
        .getElementById("customerName")
        .value
        .trim();


    const customerEmail =
      document
        .getElementById("customerEmail")
        .value
        .trim();


    const customerPhone =
      document
        .getElementById("customerPhone")
        .value
        .trim();


    const travelDate =
      document
        .getElementById("travelDate")
        .value;


    const numberOfTravelers =
      Number(
        numberOfTravelersInput.value
      );


    if (!tour) {

      bookingMessage.textContent =
        "Tour information could not be found.";

      return;

    }


    if (
      customerName === "" ||
      customerEmail === "" ||
      customerPhone === "" ||
      travelDate === "" ||
      !numberOfTravelers ||
      numberOfTravelers < 1
    ) {

      bookingMessage.textContent =
        "Please complete all the required fields.";

      return;

    }


    const totalPrice =
      calculateTotalPrice(
        numberOfTravelers
      );


    const booking = {

      tour: tour.name,

      location: tour.location,

      duration: tour.duration,

      pricePerPerson:
        getBasePrice(),

      totalPrice:
        totalPrice,

      customerName:
        customerName,

      customerEmail:
        customerEmail,

      customerPhone:
        customerPhone,

      travelDate:
        travelDate,

      numberOfTravelers:
        numberOfTravelers

    };


    localStorage.setItem(
      "tourBooking",
      JSON.stringify(booking)
    );


    /* ---------- BOOKING SUMMARY ---------- */

    document.getElementById(
      "summaryTour"
    ).textContent =
      tour.name;


    document.getElementById(
      "summaryName"
    ).textContent =
      customerName;


    document.getElementById(
      "summaryEmail"
    ).textContent =
      customerEmail;


    document.getElementById(
      "summaryDate"
    ).textContent =
      travelDate;


    document.getElementById(
      "summaryTravelers"
    ).textContent =
      numberOfTravelers;


    document.getElementById(
      "summaryPrice"
    ).textContent =
      formatPrice(totalPrice);


    document.getElementById(
      "successMessage"
    ).textContent =
      "Thank you, " +
      customerName +
      "! Your booking request for " +
      tour.name +
      " has been successfully received.";


    /* ---------- HIDE FORM ---------- */

    tourBookingForm.style.display =
      "none";


    bookingMessage.textContent =
      "";


    /* ---------- SHOW SUCCESS ---------- */

    bookingSuccess.style.display =
      "block";


    bookingSuccess.scrollIntoView({
      behavior: "smooth"
    });

  }
);


/* ---------- PAYMENT ---------- */

const makePaymentButton =
  document.getElementById(
    "makePaymentButton"
  );

const paymentMessage =
  document.getElementById(
    "paymentMessage"
  );


makePaymentButton.addEventListener(
  "click",
  function () {

    const selectedPayment =
      document.querySelector(
        'input[name="paymentMethod"]:checked'
      );


    if (!selectedPayment) {

      paymentMessage.textContent =
        "Please select a payment method.";

      return;

    }


    if (
      selectedPayment.value === "card"
    ) {

      paymentMessage.textContent =
        "Card payment will be connected to the payment gateway when the backend and payment system are added.";

    }


    if (
      selectedPayment.value === "bank"
    ) {

      paymentMessage.textContent =
        "Bank transfer payment details will be displayed here when the payment system is connected.";

    }

  }
);